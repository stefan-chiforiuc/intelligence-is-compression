#!/usr/bin/env bash
# Fetch standalone Scala 2.13 and Kotlin compilers from Maven Central.
#
# No SDKMAN, no coursier, no Gradle — just jars and `java -cp`. This keeps the
# repo's only build tooling requirement at "a JDK", and it works on a locked-down
# training laptop where you cannot install a toolchain.
#
#   bash tools/get_jvm_langs.sh
#
# Downloads ~110 MB into build/jvm-langs/ (gitignored). Idempotent.
set -euo pipefail
cd "$(dirname "$0")/.."

SCALA_V=2.13.14
KOTLIN_V=2.0.21
COROUTINES_V=1.8.1
TROVE_V=1.0.20200330
ANNOTATIONS_V=13.0

DEST=build/jvm-langs
CENTRAL=https://repo1.maven.org/maven2
mkdir -p "$DEST"

fetch() { # url, filename
  if [[ -s "$DEST/$2" ]]; then
    printf '  \033[2mhave\033[0m %s\n' "$2"
    return 0
  fi
  printf '  get  %s ... ' "$2"
  if curl -fsS --max-time 300 -o "$DEST/$2.tmp" "$1"; then
    mv "$DEST/$2.tmp" "$DEST/$2"
    echo "ok"
  else
    rm -f "$DEST/$2.tmp"
    echo "FAILED"
    return 1
  fi
}

echo "Scala $SCALA_V:"
for j in scala-compiler scala-library scala-reflect; do
  fetch "$CENTRAL/org/scala-lang/$j/$SCALA_V/$j-$SCALA_V.jar" "$j-$SCALA_V.jar"
done

echo "Kotlin $KOTLIN_V:"
fetch "$CENTRAL/org/jetbrains/kotlin/kotlin-compiler-embeddable/$KOTLIN_V/kotlin-compiler-embeddable-$KOTLIN_V.jar" \
      "kotlin-compiler-embeddable-$KOTLIN_V.jar"
for j in kotlin-stdlib kotlin-reflect kotlin-script-runtime kotlin-daemon-embeddable; do
  fetch "$CENTRAL/org/jetbrains/kotlin/$j/$KOTLIN_V/$j-$KOTLIN_V.jar" "$j-$KOTLIN_V.jar"
done
# The embeddable compiler still needs these three at run time.
fetch "$CENTRAL/org/jetbrains/kotlinx/kotlinx-coroutines-core-jvm/$COROUTINES_V/kotlinx-coroutines-core-jvm-$COROUTINES_V.jar" \
      "kotlinx-coroutines-core-jvm-$COROUTINES_V.jar"
fetch "$CENTRAL/org/jetbrains/intellij/deps/trove4j/$TROVE_V/trove4j-$TROVE_V.jar" "trove4j-$TROVE_V.jar"
fetch "$CENTRAL/org/jetbrains/annotations/$ANNOTATIONS_V/annotations-$ANNOTATIONS_V.jar" "annotations-$ANNOTATIONS_V.jar"

# Emit a tiny env file the demo scripts source, so versions live in one place.
cat > "$DEST/env.sh" <<EOF
# Generated by tools/get_jvm_langs.sh — do not edit.
SCALA_V=$SCALA_V
KOTLIN_V=$KOTLIN_V
JVMLANGS=\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)

SCALA_CP="\$JVMLANGS/scala-compiler-$SCALA_V.jar:\$JVMLANGS/scala-library-$SCALA_V.jar:\$JVMLANGS/scala-reflect-$SCALA_V.jar"
SCALA_LIB="\$JVMLANGS/scala-library-$SCALA_V.jar"
KOTLIN_CP="\$JVMLANGS/kotlin-compiler-embeddable-$KOTLIN_V.jar:\$JVMLANGS/kotlin-stdlib-$KOTLIN_V.jar:\$JVMLANGS/kotlin-reflect-$KOTLIN_V.jar:\$JVMLANGS/kotlin-script-runtime-$KOTLIN_V.jar:\$JVMLANGS/kotlin-daemon-embeddable-$KOTLIN_V.jar:\$JVMLANGS/annotations-$ANNOTATIONS_V.jar:\$JVMLANGS/kotlinx-coroutines-core-jvm-$COROUTINES_V.jar:\$JVMLANGS/trove4j-$TROVE_V.jar"
KOTLIN_LIB="\$JVMLANGS/kotlin-stdlib-$KOTLIN_V.jar"

# scalac needs -usejavacp when driven straight from a classpath like this.
scalac_() { java -cp "\$SCALA_CP" scala.tools.nsc.Main -usejavacp "\$@"; }
kotlinc_() { java -cp "\$KOTLIN_CP" org.jetbrains.kotlin.cli.jvm.K2JVMCompiler \\
               -no-stdlib -classpath "\$KOTLIN_LIB" -nowarn "\$@"; }
EOF

echo
echo "Ready. Compilers land in $DEST (gitignored)."
